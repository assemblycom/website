export type AppMark = keyof typeof APP_MARKS;

/**
 * The tints the marks are set in on a dark tile, from the brand file's coloured
 * pairings. Named by hue so a mark can be re-tinted without renaming it.
 */
export const MARK_TINTS = {
  lavender: "#B3A4F7",
  blue: "#6B84EF",
  mint: "#9BE3C0",
} as const;

export type MarkTint = keyof typeof MARK_TINTS;

/** The sheet's own opacity in the export. */
const SHEET_OPACITY = 0.8;

/**
 * Figma writes the sheet's frosting as a CSS backdrop-filter, which an inline
 * SVG has no equivalent for. It is rebuilt here: everything already painted is
 * redrawn blurred, clipped to the sheet, and the sheet is laid over that. The
 * CSS radius is twice the Gaussian deviation, which is the ratio the export's
 * own two numbers carry.
 */
const BLUR_TO_DEVIATION = 0.5;

export function AppMarkGlyph({
  mark,
  tint,
  className,
}: {
  mark: AppMark;
  tint: MarkTint;
  className?: string;
}) {
  const glyph = APP_MARKS[mark];
  const uid = useId().replace(/:/g, "");
  const color = MARK_TINTS[tint];
  const [vx, vy, vw, vh] = glyph.viewBox.split(" ").map(Number);
  const k = "scale" in glyph ? glyph.scale : 1;
  // Scaled about the mark's own centre, so the inset stays even.
  const fit =
    k === 1
      ? undefined
      : `translate(${vx + vw / 2} ${vy + vh / 2}) scale(${k}) translate(${-(vx + vw / 2)} ${-(vy + vh / 2)})`;

  return (
    <svg
      viewBox={glyph.viewBox}
      className={className}
      style={
        "flipX" in glyph && glyph.flipX
          ? { transform: "scaleX(-1)" }
          : undefined
      }
      fill="none"
      aria-hidden
    >
      <defs>
        {glyph.layers.map((layer, i) =>
          layer.role === "sheet" && layer.blur > 0 ? (
            <clipPath key={i} id={`${uid}-clip-${i}`}>
              <path d={layer.d} />
            </clipPath>
          ) : null,
        )}
        {glyph.layers.map((layer, i) =>
          layer.role === "sheet" && layer.blur > 0 ? (
            <filter
              key={i}
              id={`${uid}-blur-${i}`}
              x="-25%"
              y="-25%"
              width="150%"
              height="150%"
            >
              <feGaussianBlur stdDeviation={layer.blur * BLUR_TO_DEVIATION} />
            </filter>
          ) : null,
        )}
      </defs>

      <g transform={fit}>
        {glyph.layers.map((layer, i) => {
          if (layer.role === "solid") {
            return <path key={i} d={layer.d} fill={color} />;
          }
          // What the sheet frosts is whatever was painted under it.
          const behind = glyph.layers
            .slice(0, i)
            .filter((l) => l.role === "solid");
          return (
            <g key={i}>
              {layer.blur > 0 && behind.length > 0 && (
                <g clipPath={`url(#${uid}-clip-${i})`}>
                  <g filter={`url(#${uid}-blur-${i})`}>
                    {behind.map((l, j) => (
                      <path key={j} d={l.d} fill={color} />
                    ))}
                  </g>
                </g>
              )}
              <path d={layer.d} fill="white" fillOpacity={SHEET_OPACITY} />
            </g>
          );
        })}
      </g>
    </svg>
  );
}
