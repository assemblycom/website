const REVIEW_FIGURE =
  /<figure[^>]*>\s*<img\b[^>]*\bsrc="[^"]*?([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.[a-z]+"[^>]*>\s*(?:<figcaption>[\s\S]*?<\/figcaption>\s*)?<\/figure>/g;

/**
 * The writers follow each capture with a "Pro:" or "Con:" paragraph quoting the
 * same review, attributed by name (sometimes one of each). Under a capture that was the readable copy
 * of an image; under a card it says the review twice and splits one card from
 * the next, so it is dropped. The quote's words stay on the page in the card.
 */
const QUOTE_AFTER =
  /^((?:\s*<!--[\s\S]*?-->)*\s*)<p\b[^>]*><strong[^>]*>\s*(?:Pros?|Cons?)\s*:?\s*<\/strong>[\s\S]*?<\/p>/;

export function reviewsAsCards(html: string): string {
  let out = "";
  let rest = html;
  let found: RegExpExecArray | null;
  REVIEW_FIGURE.lastIndex = 0;
  while ((found = REVIEW_FIGURE.exec(rest))) {
    const [match, id] = found;
    const review = REVIEWS[id];
    out += rest.slice(0, found.index) + (review ? reviewCardHtml(review) : match);
    rest = rest.slice(found.index + match.length);
    REVIEW_FIGURE.lastIndex = 0;
    if (!review) continue;
    // A card can be followed by both its Pro and its Con.
    let quote: RegExpExecArray | null;
    while ((quote = QUOTE_AFTER.exec(rest)) && quote[0].includes(review.name)) {
      rest = rest.slice(quote[0].length);
    }
  }
  return out + rest;
}
